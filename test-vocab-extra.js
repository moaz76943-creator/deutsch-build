const fs = require('fs');
const path = require('path');
const filePath = path.join(__dirname, 'src/lib/deutsch/content/vocab-extra.ts');
const content = fs.readFileSync(filePath, 'utf8');
const idMatches = content.match(/id:\s*'v-extra-\d+'/g) || [];
const ids = idMatches.map(m => m.match(/'([^']+)'/)[1]);
const uniqueIds = new Set(ids);
console.log(`Found ${ids.length} items, ${uniqueIds.size} unique IDs`);
if (ids.length !== uniqueIds.size || ids.length < 30) process.exit(1);
if (!content.includes('präteritum') || !content.includes("article: 'der'")) process.exit(1);
console.log('PASS: vocab-extra.ts validation successful');
process.exit(0);
