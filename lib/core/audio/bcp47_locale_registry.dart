  static String? getBcp47Locale(String languageId) {
    return _catalogToBcp47[languageId];
  }

  static String? getFallbackLocale(String bcp47Locale) {
    return _regionalFallbacks[bcp47Locale];
  }

  /// Never fall back silently to English or German unless they are the requested languages.
  static List<String> resolveCandidates(String languageId) {
    final bcp47 = getBcp47Locale(languageId);
    if (bcp47 == null) return [];
    final fallback = getFallbackLocale(bcp47);
    if (fallback != null && fallback != bcp47) {
      return [bcp47, fallback];
    }
    return [bcp47];
  }
