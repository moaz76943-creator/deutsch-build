import 'package:deutsch_bilarabi/core/cache/cache_identity.dart';
import 'package:deutsch_bilarabi/core/cache/lru_memory_cache.dart';

class L1VocabularyCache {
  static final L1VocabularyCache _instance = L1VocabularyCache._internal();
  factory L1VocabularyCache() => _instance;

  L1VocabularyCache._internal() {
    _memoryCache = LruMemoryCache<String, List<Map<String, dynamic>>>(
      maxCapacity: 50,
      maxMemoryBytes: 5 * 1024 * 1024, // 5MB budget per requirements
      onEvict: (key) {
        _identities.remove(key);
      },
    );
  }

  late final LruMemoryCache<String, List<Map<String, dynamic>>> _memoryCache;
  final Map<String, CacheIdentity> _identities = {};

  int get currentMemoryBytes => _memoryCache.currentMemoryBytes;

  String generateKey(String language, String direction, String contentVersion) {
    return '${language}_${direction}_$contentVersion';
  }

  int _measureSize(List<Map<String, dynamic>> items) {
    int size = 0;
    for (final item in items) {
      for (final entry in item.entries) {
        size += entry.key.length * 2;
        if (entry.value is String) {
          size += (entry.value as String).length * 2;
        } else if (entry.value is num) {
          size += 8;
        } else if (entry.value is bool) {
          size += 1;
        } else {
          size += 16;
        }
      }
    }
    return size;
  }

  String _internalKey(String key, String? direction, dynamic packVersion) {
     if (direction == null && packVersion == null) return key;
     return '${key}_${direction ?? "default"}_${packVersion?.toString() ?? "1.0.0"}';
  }

  void putWithIdentity(String key, List<Map<String, dynamic>> items, CacheIdentity identity) {
    String actualKey = _internalKey(key, identity.direction, identity.contentVersion);
    if (_identities.containsKey(actualKey)) {
      final existingIdentity = _identities[actualKey]!;
      if (existingIdentity.language == identity.language &&
          existingIdentity.direction == identity.direction &&
          existingIdentity.contentVersion == identity.contentVersion &&
          existingIdentity.pairEpoch > identity.pairEpoch) {
        return;
      }
    }

    _invalidateStaleIdentity(identity);
    final success = _memoryCache.put(actualKey, List.unmodifiable(items), itemSizeBytes: _measureSize(items));
    if (success) {
      _identities[actualKey] = identity;
    }
  }

  void _invalidateStaleIdentity(CacheIdentity newIdentity) {
    final keysToRemove = <String>[];
    for (final entry in _identities.entries) {
      final id = entry.value;
      if (id.language == newIdentity.language && id.direction == newIdentity.direction) {
        if (id.pairEpoch < newIdentity.pairEpoch) {
          keysToRemove.add(entry.key);
        }
      }
    }
    for (final k in keysToRemove) {
      _memoryCache.remove(k);
      _identities.remove(k);
    }
  }

  void put(
    String key,
    List<Map<String, dynamic>> items, {
    String? direction,
    dynamic packVersion,
    int? requestEpoch,
    int? activeEpoch,
  }) {
    if (requestEpoch != null && activeEpoch != null && requestEpoch < activeEpoch) {
      return;
    }

    final dir = direction ?? 'default';
    final ver = packVersion?.toString() ?? '1.0.0';

    String lang = key;
    String d = dir;
    String v = ver;

    // If the key was generated by generateKey, it has the format lang_dir_version
    final parts = key.split('_');
    if (parts.length >= 3 && direction == null && packVersion == null) {
      lang = parts[0];
      d = parts.sublist(1, parts.length - 1).join('_'); // handle direction with underscore
      v = parts.last;

      // Simple heuristic: if it looks like a version (e.g. 1.0.0), assume it's generated
      if (v.contains('.')) {
         // good to go
      } else {
         lang = key;
         d = dir;
         v = ver;
      }
    }

    final identity = CacheIdentity(
      language: lang,
      direction: d,
      pairEpoch: requestEpoch ?? 0,
      contentVersion: v,
    );

    // Some tests use put(generateKey(...)). We want to support that as well.
    // If key contains '_', we assume it's already a composite key generated by generateKey.
    String actualKey = key;
    if (direction != null || packVersion != null) {
       actualKey = _internalKey(key, direction, packVersion);
    }

    if (_identities.containsKey(actualKey)) {
      final existingIdentity = _identities[actualKey]!;
      if (existingIdentity.language == identity.language &&
          existingIdentity.direction == identity.direction &&
          existingIdentity.contentVersion == identity.contentVersion &&
          existingIdentity.pairEpoch > identity.pairEpoch) {
        return;
      }
    }

    final keysToRemove = <String>[];
    for (final entry in _identities.entries) {
      final id = entry.value;
      if (id.language == identity.language && id.direction == identity.direction) {
        if (id.pairEpoch < identity.pairEpoch) {
          keysToRemove.add(entry.key);
        }
      }
    }
    for (final k in keysToRemove) {
      _memoryCache.remove(k);
      _identities.remove(k);
    }

    final success = _memoryCache.put(actualKey, List.unmodifiable(items), itemSizeBytes: _measureSize(items));
    if (success) {
      _identities[actualKey] = identity;
    }
  }

  List<Map<String, dynamic>>? get(
    String key, {
    String? direction,
    dynamic packVersion,
  }) {
    String actualKey = key;
    if (direction != null || packVersion != null) {
       actualKey = _internalKey(key, direction, packVersion);
    }

    if (_memoryCache.containsKey(actualKey)) {
        return _memoryCache.get(actualKey);
    }

    // Fallback if test used the generated string directly
    if (_memoryCache.containsKey(key)) {
        return _memoryCache.get(key);
    }
    return null;
  }

  bool has(
    String key, {
    String? direction,
    dynamic packVersion,
  }) {
    String actualKey = key;
    if (direction != null || packVersion != null) {
       actualKey = _internalKey(key, direction, packVersion);
    }

    if (_memoryCache.containsKey(actualKey)) {
        return true;
    }
    // Fallback if test used the generated string directly
    return _memoryCache.containsKey(key);
  }

  void invalidateStaleVersions(String activeVersion) {
    final keysToRemove = <String>[];
    for (final entry in _identities.entries) {
      if (entry.value.contentVersion != activeVersion) {
        keysToRemove.add(entry.key);
      }
    }
    for (final k in keysToRemove) {
      _memoryCache.remove(k);
      _identities.remove(k);
    }
  }

  void invalidateStale(String language, String direction, dynamic activeVersion) {
    final keysToRemove = <String>[];
    for (final entry in _identities.entries) {
      final id = entry.value;
      if (id.language == language && id.direction == direction && id.contentVersion != activeVersion.toString()) {
        keysToRemove.add(entry.key);
      }
    }
    for (final k in keysToRemove) {
      _memoryCache.remove(k);
      _identities.remove(k);
    }
  }

  void clear() {
    _memoryCache.clear();
  }

  void onMemoryPressure() {
    _memoryCache.trimMemoryPressure();
  }

  void trimMemoryPressure() {
    _memoryCache.trimMemoryPressure();
  }
}
